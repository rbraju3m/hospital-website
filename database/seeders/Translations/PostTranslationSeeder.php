**২. যেটা কাজ করবে, এটাই কি সবচেয়ে সংকীর্ণ ওষুধ?**

ব্রড-স্পেকট্রাম অ্যান্টিবায়োটিক বেশি ধরনের জীবাণু মারে, যার মধ্যে অন্ত্রের উপকারী জীবাণুও পড়ে, আর প্রতিরোধ তৈরিতে বেশি ভূমিকা রাখে। সম্ভাব্য জীবাণুটির জন্য যেখানে সংকীর্ণ-পরিসরের ওষুধেই কাজ হবে, সেখানে সেটিই ভালো পছন্দ।

**৩. আগে কালচার করা উচিত কি?**

মূত্রনালির সংক্রমণ, ক্ষতের সংক্রমণ ও বারবার হওয়া সমস্যায় কালচার ও সেনসিটিভিটি পরীক্ষা প্রকৃত জীবাণুটি এবং কোন ওষুধে তা সাড়া দেয় তা শনাক্ত করে। এতে দিন দুয়েক লাগে, কিন্তু অনুমানের জায়গায় নিশ্চিত জ্ঞান আসে — আর বারবার হওয়া সংক্রমণে অনুমান তো এর মধ্যেই ব্যর্থ হয়েছে।

**৪. ঠিক কত দিন?**

প্রমাণ জমার সাথে সাথে অনেক সংক্রমণে কোর্সের দৈর্ঘ্য কমে এসেছে। নির্দিষ্ট দিনসংখ্যা জেনে নিন এবং কোর্স শেষ করুন। ভালো লাগতে শুরু করলেই বন্ধ করে দিলে সবচেয়ে শক্ত জীবাণুগুলোই টিকে যায় — ঠিক যে দলটিকে আপনি বাঁচিয়ে রাখতে চান না।

