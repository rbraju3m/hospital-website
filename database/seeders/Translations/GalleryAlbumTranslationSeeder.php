    public function run(): void
    {
        foreach ($this->albums() as $slug => $data) {
            $album = GalleryAlbum::where('slug', $slug)->first();

            if (! $album) {
                continue;
            }

            $captions = $data['photos'] ?? [];
            unset($data['photos']);

            $album->setTranslations('bn', $data)->save();

            // Captions are matched by position, the same key the English seeder
            // writes them under — a photograph has no slug of its own.
            foreach ($album->photos()->get() as $photo) {
                if ($caption = $captions[$photo->sort_order] ?? null) {
                    $photo->setTranslations('bn', ['caption' => $caption])->save();
                }
            }
        }
    }

